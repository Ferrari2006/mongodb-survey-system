// UI authoring smoke check; run after browser_flow.js with the demo owner signed in.
async (page) => {
  await page.goto('http://127.0.0.1:5052/');
  await page.getByRole('button',{name:'新建问卷',exact:true}).click();
  await page.getByRole('textbox',{name:'问卷标题',exact:true}).fill('浏览器配置验证');
  await page.locator('#allow-anonymous').check();
  await page.locator('#allow-repeat').check();
  await page.getByRole('button',{name:'保存基本信息',exact:true}).click();
  await page.getByText('问卷已保存',{exact:true}).waitFor();
  await page.locator('#question-id').fill('branch');
  await page.locator('#question-title').fill('路线选择');
  await page.locator('#question-options').fill('a | 完整填写\nb | 直接评分');
  await page.locator('#question-required').check();
  await page.locator('#jump-value').fill('b');
  await page.locator('#jump-target').fill('score');
  await page.getByRole('button',{name:'加入规则',exact:true}).click();
  await page.getByRole('button',{name:'保存题目',exact:true}).click();
  await page.getByText('1. 路线选择',{exact:true}).waitFor();
  await page.locator('#question-id').fill('services');
  await page.locator('#question-title').fill('选择两个服务');
  await page.locator('#question-type').selectOption('multiple');
  await page.locator('#question-options').fill('a | 图书馆\nb | 食堂\nc | 体育馆');
  await page.locator('#question-min').fill('2');
  await page.locator('#question-max').fill('2');
  await page.locator('#question-required').check();
  await page.getByRole('button',{name:'保存题目',exact:true}).click();
  await page.getByText('2. 选择两个服务',{exact:true}).waitFor();
  await page.locator('#question-id').fill('score');
  await page.locator('#question-title').fill('评分');
  await page.locator('#question-type').selectOption('number');
  await page.locator('#question-min').fill('0');
  await page.locator('#question-max').fill('10');
  await page.locator('#question-integer').check();
  await page.getByRole('button',{name:'保存题目',exact:true}).click();
  await page.getByText('3. 评分',{exact:true}).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button',{name:'发布问卷',exact:true}).click();
  await page.getByText('发布成功，可复制分享链接。',{exact:true}).waitFor();
  const share = await page.locator('#share-url').inputValue();
  if(!share.includes('/survey/'))throw new Error('Missing share URL');
  if(await page.locator('#question-form').isVisible())throw new Error('Published editor not frozen');
  await page.goto(share);
  await page.getByRole('radio',{name:'直接评分',exact:true}).check();
  await page.getByRole('button',{name:'下一题',exact:true}).click();
  await page.getByText('评分（选答）',{exact:true}).waitFor();
  await page.getByRole('spinbutton',{name:'填写答案',exact:true}).fill('9');
  await page.getByRole('button',{name:'下一题',exact:true}).click();
  await page.getByText('回答已完成，请确认提交',{exact:true}).waitFor();
  await page.getByRole('button',{name:'返回修改最后一题',exact:true}).click();
  await page.getByText('评分（选答）',{exact:true}).waitFor();
  await page.getByRole('spinbutton',{name:'填写答案',exact:true}).fill('7');
  await page.getByRole('button',{name:'下一题',exact:true}).click();
  await page.getByRole('button',{name:'提交问卷',exact:true}).click();
  await page.getByText('提交成功，感谢填写',{exact:true}).waitFor();
  await page.goto('http://127.0.0.1:5052/');
  await page.locator('#survey-list article').filter({hasText:'浏览器配置验证'}).getByRole('button',{name:'管理问卷',exact:true}).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button',{name:'关闭问卷',exact:true}).click();
  await page.getByText('问卷已关闭',{exact:true}).waitFor();
  await page.goto(share);
  await page.getByText('问卷未发布、已关闭或不存在',{exact:true}).waitFor();
}
