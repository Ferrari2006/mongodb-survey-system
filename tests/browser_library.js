// Browser smoke check: pass a Playwright Page connected to the isolated test server.
async (page) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5052/');
  const name='browser_lib_'+Date.now();
  await page.locator('#username').fill(name);
  await page.locator('#password').fill('Browser-test-123');
  await page.locator('#register').click();
  await page.getByText('注册成功，请点击登录。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'登录',exact:true}).click();
  await page.locator('#identity').getByText(name,{exact:false}).waitFor();
  await page.locator('#open-library').click();
  page.once('dialog',d=>d.accept('浏览器测试题库'));
  await page.locator('#bank-new').click();
  await page.locator('#library-bank option').filter({hasText:'浏览器测试题库'}).waitFor({state:'attached'});
  await page.locator('#library-new').click();
  await page.locator('#library-title').fill('共享与版本测试题');
  await page.locator('#library-save').click();
  await page.getByText('已创建题目及首个版本',{exact:true}).waitFor();
  await page.locator('#library-title').fill('新的工作稿标题');
  await page.locator('#library-save').click();
  await page.getByText('工作稿已保存，现有版本未改变',{exact:true}).waitFor();
  if(await page.locator('#library-version option').count()!==1)throw Error('Working copy unexpectedly created version');
  await page.locator('#library-commit').click();
  await page.getByText('新版本已提交，旧版本与旧问卷保持原样',{exact:true}).waitFor();
  if(await page.locator('#library-version option').count()!==2)throw Error('New version missing');
  const first=await page.locator('#library-version option').first().getAttribute('value');
  await page.locator('#library-version').selectOption(first);
  await page.locator('#library-preview').getByText('共享与版本测试题',{exact:true}).waitFor();
  page.once('dialog',d=>d.accept());await page.locator('#library-restore').click();
  await page.getByText('已恢复并生成新版本',{exact:true}).waitFor();
  await page.locator('#library-back').click();await page.locator('#new-survey').click();
  await page.locator('#survey-title').fill('题库引用浏览器验证');
  await page.locator('#survey-form button[type=submit]').click();
  await page.getByText('问卷已保存',{exact:true}).waitFor();
  await page.locator('#import-library').click();
  await page.getByRole('button',{name:'查看版本与使用',exact:true}).click();
  await page.locator('#library-version').selectOption(first);
  page.once('dialog',d=>d.accept('imported'));await page.locator('#library-use').click();
  await page.getByText('指定版本已加入问卷，可返回调整顺序与跳转',{exact:true}).waitFor();
  await page.locator('#library-usage').click();
  await page.locator('#library-result').getByText(/题库引用浏览器验证/).waitFor();
  await page.locator('#library-back').click();
  await page.locator('#question-list').getByText('1. 共享与版本测试题',{exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile overflow');
  await page.screenshot({path:'output/playwright/stage2-library-mobile.png',fullPage:true});
  if(errors.length)throw Error(errors.join('\n'));
  return {successful:true,username:name,flows:['bank','working copy','commit','restore','old-version import','usage','mobile layout'],pageErrors:errors};
}
